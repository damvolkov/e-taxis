"""transpiler.map — the persona equivalence map: every core slot and the document · block each backend renders it into.

Read-only and deterministic: it reads the slot registries (`core/base` plus the facets the harness
grants) and each backend's persona spec, and never touches a live tree. The console view splits the
corpus into its two areas (tekton · nomos); the markdown view is the same map for the site, the
page `op transpiler map` writes.
"""

from __future__ import annotations

from collections.abc import Mapping
from pathlib import Path

from ops.core.settings import settings
from ops.models.entity import BACKENDS, FACETS, Backend, Harness
from ops.transpiler.render import Transpiler


class PersonaMap:
    """The persona equivalences: slot × backend → document · block, one area per harness."""

    def __init__(self, root: Path | None = None) -> None:
        self.root = (root or settings.ROOT).resolve()

    ##### PRIVATE #####

    def _common_reader(self, backend: Backend) -> Transpiler:
        """A read-only transpiler over the corpus.
        ### The scratch out is the `specs` convention: the map stays off every live tree whatever the backend.
        """
        return Transpiler(self.root, backend, settings.reports_dir / ".map-scratch")

    def _common_cells(self, backend: Backend) -> Mapping[str, str]:
        """Slot → every place the backend's spec renders it: `document · block`, joined when there are several."""
        where: dict[str, list[str]] = {}
        for doc in self._common_reader(backend).documents:
            for block in doc.blocks:
                for slot in block.slots:
                    where.setdefault(slot, []).append(f"{doc.target} · {block.heading or block.type}")
        return {slot: "; ".join(places) for slot, places in where.items()}

    def _common_title(self, harness: Harness) -> str:
        """The area's one line: what composes it, and the backends its columns show."""
        layers = " + ".join(("core/base", *(f"core/{facet.value}" for facet in FACETS[harness])))
        backends = " · ".join(backend.value for backend in BACKENDS[harness])
        return f"{harness.value.upper()} · {layers} → {backends}"

    def _text_area(self, harness: Harness) -> str:
        """One console area: the title, then the grid with columns padded to their widest cell."""
        grid = self.grid(harness)
        widths = [max(len(row[column]) for row in grid) for column in range(len(grid[0]))]
        body = ["  ".join(cell.ljust(width) for cell, width in zip(row, widths, strict=True)) for row in grid]
        return "\n".join((self._common_title(harness), *body))

    def _markdown_area(self, harness: Harness) -> str:
        """One docs section: the title as its heading, the grid as a markdown table."""
        grid = self.grid(harness)
        rows = ["| " + " | ".join(row) + " |" for row in grid]
        divider = "|" + "---|" * len(grid[0])
        return "\n".join((f"## {self._common_title(harness)}", *rows[:1], divider, *rows[1:]))

    ############################################################

    ##### PUBLIC #####

    def grid(self, harness: Harness) -> tuple[tuple[str, ...], ...]:
        """A header and one row per slot the harness may render, in registry order: source, slot, one cell per backend."""
        backends = BACKENDS[harness]
        slots = {
            slot: "(inline)" if path is None else str(path.relative_to(self.root))
            for slot, path in self._common_reader(backends[0]).sources.items()
        }
        cells = {backend: self._common_cells(backend) for backend in backends}
        head = ("source", "slot", *(backend.value for backend in backends))
        rows = tuple(
            (source, slot, *(cells[backend].get(slot, "—") for backend in backends)) for slot, source in slots.items()
        )
        return (head, *rows)

    def text(self) -> str:
        """The whole map for the terminal: one aligned table per harness area."""
        return "\n\n".join(self._text_area(harness) for harness in Harness)

    def markdown(self) -> str:
        """The whole map as the docs page: one table per harness area, under a generated header."""
        areas = [self._markdown_area(harness) for harness in Harness]
        intro = (
            "# Persona equivalence map\n\n"
            "Every persona slot of the core and the document · block each backend's spec renders it into. "
            "Generated by `op transpiler map` from `core/*/persona.yaml` and `specs/*/persona.yaml`: "
            "do not edit — rerun the command."
        )
        return "\n\n".join((intro, *areas))
